export type EmailLocale = 'fr' | 'en' | 'de' | 'es' | 'it' | 'nl' | 'pt' | 'da' | 'hu';

export const SUPPORTED_EMAIL_LOCALES: EmailLocale[] = ['fr', 'en', 'de', 'es', 'it', 'nl', 'pt', 'da', 'hu'];

export function normalizeEmailLocale(locale?: string | null): EmailLocale {
  if (!locale) return 'fr';
  const clean = locale.toLowerCase().split('-')[0].trim() as EmailLocale;
  return SUPPORTED_EMAIL_LOCALES.includes(clean) ? clean : 'fr';
}

export function formatEmailPrice(price: number, currency: string = 'EUR', locale: EmailLocale = 'fr'): string {
  const locMap: Record<EmailLocale, string> = {
    fr: 'fr-FR',
    en: 'en-US',
    de: 'de-DE',
    es: 'es-ES',
    it: 'it-IT',
    nl: 'nl-NL',
    pt: 'pt-PT',
    da: 'da-DK',
    hu: 'hu-HU',
  };
  const intlLocale = locMap[locale] || 'fr-FR';
  try {
    return new Intl.NumberFormat(intlLocale, {
      style: 'currency',
      currency: currency || 'EUR',
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(price);
  } catch {
    return `${price.toFixed(2)} ${currency}`;
  }
}

export function formatEmailDate(date: Date, locale: EmailLocale = 'fr'): string {
  const locMap: Record<EmailLocale, string> = {
    fr: 'fr-FR',
    en: 'en-US',
    de: 'de-DE',
    es: 'es-ES',
    it: 'it-IT',
    nl: 'nl-NL',
    pt: 'pt-PT',
    da: 'da-DK',
    hu: 'hu-HU',
  };
  const intlLocale = locMap[locale] || 'fr-FR';
  try {
    return new Intl.DateTimeFormat(intlLocale, { dateStyle: 'long' }).format(date);
  } catch {
    return date.toLocaleDateString();
  }
}

